class Pokemon:
    def __init__(
            self,
            name,
            pokemon_type,
            hp,
            attack,
            defence,
            special_attack,
            special_defence,
            speed
    ):
        self.name = name
        self.pokemon_type = pokemon_type
        self.hp = hp
        self.attack = attack
        self.defence = defence
        self.special_attack = special_attack
        self.special_defence = special_defence
        self.speed = speed
